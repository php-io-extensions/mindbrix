<?php

/*
 * Writes src/shaders.inc: Rasterizer's Metal shader source as one C string, with
 * the one header it imports ("Rasterizer.h") inlined, because a library compiled
 * from source at run time (newLibraryWithSource:) has no include path.
 *
 * Run after updating lib/Rasterizer; tests/ShadersTest.php fails while the
 * committed file differs from what this writes.
 *
 *   php tools/shaders.php            # rewrite src/shaders.inc
 *   php tools/shaders.php --print    # print it instead
 */

$root = dirname(__DIR__);
$include = $root . '/lib/Rasterizer/Package/Sources/RasterizerCpp/include';

$shader = file_get_contents($include . '/Shaders.metal');
$header = file_get_contents($include . '/Rasterizer.h');
if ($shader === false || $header === false) {
    fwrite(STDERR, "missing vendored shader sources under $include\n");
    exit(1);
}

$source = str_replace("#import \"Rasterizer.h\"\n", $header . "\n", $shader, $count);
if ($count !== 1) {
    fwrite(STDERR, "expected exactly one #import \"Rasterizer.h\" in Shaders.metal, found $count\n");
    exit(1);
}

/* One C string literal per source line; backslash, quote and bytes outside printable ASCII escaped as octal. */
$escape = static function (string $line): string {
    $out = '';
    foreach (str_split($line) as $c) {
        $o = ord($c);
        $out .= match (true) {
            $c === '\\' => '\\\\',
            $c === '"' => '\\"',
            $c === '?' => '\\?',
            $o < 0x20 || $o > 0x7e => sprintf('\\%03o', $o),
            default => $c,
        };
    }
    return $out;
};

$lines = explode("\n", $source);
$body = '';
foreach ($lines as $i => $line) {
    $newline = $i < count($lines) - 1 ? '\\n' : '';
    $body .= "\t\"" . $escape($line) . $newline . "\"\n";
}

$inc = "/* Generated by tools/shaders.php from lib/Rasterizer: do not edit. */\n"
    . "static const char mindbrix_shader_text[] =\n" . $body . ";\n";

if (in_array('--print', $argv, true)) {
    echo $inc;
} else {
    file_put_contents($root . '/src/shaders.inc', $inc);
}
